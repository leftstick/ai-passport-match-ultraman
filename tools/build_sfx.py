#!/usr/bin/env python3
"""Convert selected CC0 Kenney clips into main/audio/sfx.c.

The Kenney packs are not committed (about 9 MB each). Download them from
https://kenney.nl/assets/{impact-sounds,interface-sounds,sci-fi-sounds,music-jingles}
and extract them into one directory, then run:

    python tools/build_sfx.py --source-dir /path/to/kenney

Output is 16 kHz mono signed 16-bit PCM. Each clip is peak-normalised to
-3 dBFS and gets a 5 ms fade so playback never starts or ends with a click.
"""

import argparse
import pathlib
import subprocess
import sys
import tempfile

RATE = 16000
PEAK = 0.708  # -3 dBFS
FADE_MS = 5

# (enum name, source path relative to --source-dir, max seconds)
CLIPS = [
    ("SFX_MOVE", "interface-sounds/Audio/click_001.ogg", 0.30),
    ("SFX_CONFIRM", "interface-sounds/Audio/confirmation_002.ogg", 0.80),
    ("SFX_CORRECT", "music-jingles/Audio/Pizzicato jingles/jingles_PIZZI00.ogg", 0.70),
    ("SFX_WRONG", "interface-sounds/Audio/error_004.ogg", 0.40),
    ("SFX_HINT", "interface-sounds/Audio/question_003.ogg", 0.60),
    ("SFX_HIT", "impact-sounds/Audio/impactPunch_medium_002.ogg", 0.80),
    ("SFX_CRITICAL", "sci-fi-sounds/Audio/laserSmall_000.ogg", 0.50),
    ("SFX_HURT", "impact-sounds/Audio/impactSoft_heavy_001.ogg", 0.80),
    ("SFX_CHARGE", "sci-fi-sounds/Audio/forceField_000.ogg", 1.10),
    ("SFX_BEAM", "sci-fi-sounds/Audio/laserLarge_000.ogg", 0.90),
    ("SFX_MONSTER_DOWN", "sci-fi-sounds/Audio/explosionCrunch_000.ogg", 1.00),
    ("SFX_VICTORY", "music-jingles/Audio/Pizzicato jingles/jingles_PIZZI10.ogg", 1.10),
    ("SFX_DEFEAT", "music-jingles/Audio/8-Bit jingles/jingles_NES05.ogg", 1.20),
    ("SFX_PAUSE", "interface-sounds/Audio/back_002.ogg", 0.35),
]


def decode(path: pathlib.Path, limit: float) -> list[int]:
    with tempfile.NamedTemporaryFile(suffix=".s16", delete=False) as tmp:
        raw = pathlib.Path(tmp.name)
    try:
        subprocess.run(
            [
                "ffmpeg", "-v", "error", "-y", "-i", str(path),
                "-ac", "1", "-ar", str(RATE), "-f", "s16le",
                "-t", f"{limit:.3f}", str(raw),
            ],
            check=True,
        )
        data = raw.read_bytes()
    finally:
        raw.unlink(missing_ok=True)
    return [int.from_bytes(data[i:i + 2], "little", signed=True)
            for i in range(0, len(data), 2)]


def process(samples: list[int]) -> list[int]:
    if not samples:
        return samples
    fade = max(1, RATE * FADE_MS // 1000)
    fade = min(fade, len(samples) // 2) or 1
    for i in range(fade):
        gain = i / fade
        samples[i] = int(samples[i] * gain)
        samples[-1 - i] = int(samples[-1 - i] * gain)
    peak = max(abs(v) for v in samples) or 1
    scale = PEAK * 32767 / peak
    return [max(-32768, min(32767, int(round(v * scale)))) for v in samples]


def c_array(name: str, samples: list[int]) -> str:
    lines = [f"static const int16_t {name}[] = {{"]
    for i in range(0, len(samples), 12):
        rows = ", ".join(str(v) for v in samples[i:i + 12])
        lines.append(f"    {rows},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source-dir", required=True, type=pathlib.Path)
    parser.add_argument("--output", default="main/audio/sfx.c", type=pathlib.Path)
    args = parser.parse_args()

    chunks = [
        "// Generated by tools/build_sfx.py. Do not edit by hand.\n"
        "// Source clips: Kenney (CC0 1.0). See assets/audio/SOURCES.md.\n"
        '#include "sfx.h"\n\n'
    ]
    table = []
    total = 0
    for enum_name, rel, limit in CLIPS:
        source = args.source_dir / rel
        if not source.is_file():
            print(f"ERROR: missing {source}", file=sys.stderr)
            return 1
        samples = process(decode(source, limit))
        if not samples:
            print(f"ERROR: empty audio for {rel}", file=sys.stderr)
            return 1
        total += len(samples)
        array = f"clip_{enum_name.lower()}"
        chunks.append(c_array(array, samples))
        chunks.append("")
        table.append((enum_name, array, len(samples)))
        print(f"{enum_name:18s} {len(samples) / RATE:5.3f}s  {rel}")

    chunks.append("static const sfx_clip_t CLIPS[SFX_COUNT] = {")
    for enum_name, array, count in table:
        chunks.append(f"    [{enum_name}] = {{ .samples = {array}, .count = {count} }},")
    chunks.append("};\n")
    chunks.append("const sfx_clip_t *sfx_clip(sfx_id_t id)")
    chunks.append("{")
    chunks.append("    if ((unsigned)id >= (unsigned)SFX_COUNT) {")
    chunks.append("        return NULL;")
    chunks.append("    }")
    chunks.append("    return &CLIPS[id];")
    chunks.append("}")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(chunks) + "\n", encoding="utf-8")
    print(f"Wrote {args.output} ({total * 2} bytes PCM)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
