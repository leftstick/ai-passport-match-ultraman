#!/usr/bin/env python3
"""Synthesise the two procedural battle cues into main/audio/sfx_extra.c.

The Kenney source packs used by tools/build_sfx.py are not required here: both
clips are generated from scratch so the repository stays self-contained.
"""

from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "main" / "audio" / "sfx_extra.c"
RATE = 16000


class Lcg:
    def __init__(self, seed: int) -> None:
        self.state = seed & 0xFFFFFFFF

    def unit(self) -> float:
        self.state = (1664525 * self.state + 1013904223) & 0xFFFFFFFF
        return (self.state / 0xFFFFFFFF) * 2.0 - 1.0


def swing() -> list[int]:
    n = int(RATE * 0.18)
    rng = Lcg(0x51A7)
    out: list[float] = []
    lp = 0.0
    for i in range(n):
        u = i / n
        env = (u / 0.06) if u < 0.06 else math.exp(-4.2 * (u - 0.06))
        # Low-pass cutoff sweeps open then closed to give the whoosh its bite.
        alpha = 0.05 + 0.55 * math.sin(math.pi * min(u * 1.4, 1.0))
        lp += alpha * (rng.unit() - lp)
        sweep = math.sin(2 * math.pi * (760.0 - 520.0 * u) * (i / RATE))
        out.append(env * (0.72 * lp + 0.28 * sweep))
    return normalise(out, 0.7)


def growl() -> list[int]:
    n = int(RATE * 0.55)
    rng = Lcg(0x6B0A)
    out: list[float] = []
    phase = 0.0
    for i in range(n):
        t = i / RATE
        u = i / n
        freq = 82.0 + 9.0 * math.sin(2 * math.pi * 5.0 * t)
        phase += 2 * math.pi * freq / RATE
        body = (0.55 * math.sin(phase) +
                0.25 * math.sin(2 * phase + 0.5) +
                0.12 * math.sin(3 * phase))
        grit = rng.unit() * 0.12
        if u < 0.12:
            env = u / 0.12
        elif u > 0.78:
            env = (1.0 - u) / 0.22
        else:
            env = 1.0
        # A slow pulse makes the growl feel like it comes from a throat.
        pulse = 0.85 + 0.15 * math.sin(2 * math.pi * 23.0 * t)
        out.append(env * pulse * (body + grit))
    return normalise(out, 0.65)


def normalise(samples: list[float], peak: float) -> list[int]:
    top = max(abs(v) for v in samples) or 1.0
    scale = peak * 32767.0 / top
    return [max(-32768, min(32767, int(round(v * scale)))) for v in samples]


def emit_array(name: str, samples: list[int]) -> str:
    lines = [f"static const int16_t {name}[] = {{"]
    for i in range(0, len(samples), 12):
        chunk = ", ".join(str(v) for v in samples[i:i + 12])
        lines.append(f"    {chunk},")
    lines.append("};")
    return "\n".join(lines)


def main() -> int:
    swing_samples = swing()
    growl_samples = growl()
    body = "\n\n".join([
        "// Generated by tools/build_sfx_extra.py. Do not edit by hand.",
        '#include "sfx_extra.h"',
        "// Procedural whoosh played on the attack windup.",
        emit_array("clip_sfx_swing", swing_samples),
        "// Procedural monster growl played when the enemy lunges.",
        emit_array("clip_sfx_growl", growl_samples),
        "const sfx_clip_t *sfx_extra_clip(sfx_id_t id)\n"
        "{\n"
        "    if (id == SFX_SWING) {\n"
        "        static const sfx_clip_t clip = {\n"
        "            .samples = clip_sfx_swing,\n"
        f"            .count = {len(swing_samples)},\n"
        "        };\n"
        "        return &clip;\n"
        "    }\n"
        "    if (id == SFX_GROWL) {\n"
        "        static const sfx_clip_t clip = {\n"
        "            .samples = clip_sfx_growl,\n"
        f"            .count = {len(growl_samples)},\n"
        "        };\n"
        "        return &clip;\n"
        "    }\n"
        "    return 0;\n"
        "}",
    ])
    OUT.write_text(body + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} "
          f"({len(swing_samples) + len(growl_samples)} samples)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
