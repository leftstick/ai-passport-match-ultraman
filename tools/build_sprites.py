#!/usr/bin/env python3
"""Convert the pixel-heroes PNGs into compact LVGL RGB565A8 C arrays.

The source art is 512x512. The device panel is 240x320 and has no PSRAM, so the
sprites are trimmed, nearest-neighbour scaled to a game-sized canvas, and stored
as RGB565 + A8 (3 bytes per pixel). Run from the repository root:

    python tools/build_sprites.py

Every hero contributes eight action poses and every monster five, which the
battle UI switches between to reflect what just happened.
"""
from __future__ import annotations

import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:
    sys.exit("Pillow is required: python -m pip install pillow")

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "pixel-heroes"
OUT_C = ROOT / "main" / "assets" / "sprites.c"
OUT_H = ROOT / "main" / "assets" / "sprites.h"

HERO_W, HERO_H = 72, 88
MONSTER_W, MONSTER_H = 80, 80
ALPHA_CUTOFF = 8

HEROES = [
    ("blue", "blue"),
    ("red", "red"),
    ("emerald", "emerald"),
    ("gold", "gold"),
    ("violet", "violet"),
]
HERO_POSES = [
    ("idle", 1),
    ("fight", 2),
    ("fly", 3),
    ("beam", 4),
    ("charge", 5),
    ("kick", 6),
    ("guard", 7),
    ("victory", 8),
]
MONSTERS = [
    ("spiker", "spiker", 1),
    ("brute", "brute", 2),
    ("abyss", "abyss", 3),
    ("moth", "winged-moth", 4),
    ("ape", "ape", 5),
    ("bladehead", "bladehead", 6),
    ("beetle", "beetle", 8),
    ("wyvern", "wyvern", 7),
]
MONSTER_POSES = [
    ("idle", 1),
    ("attack", 2),
    ("roar", 3),
    ("charge", 4),
    ("hurt", 5),
]


def load_fitted(path: Path, width: int, height: int) -> Image.Image:
    image = Image.open(path).convert("RGBA")
    alpha = image.getchannel("A").point(lambda value: 255 if value > ALPHA_CUTOFF else 0)
    bbox = alpha.getbbox()
    if bbox is None:
        raise SystemExit(f"empty alpha channel: {path}")
    image = image.crop(bbox)
    scale = min(width / image.width, height / image.height)
    size = (max(1, round(image.width * scale)), max(1, round(image.height * scale)))
    image = image.resize(size, Image.NEAREST)
    canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    canvas.alpha_composite(image, ((width - size[0]) // 2, height - size[1]))
    return canvas


def rgb565a8(image: Image.Image) -> bytes:
    pixels = image.load()
    color = bytearray()
    alpha = bytearray()
    for y in range(image.height):
        for x in range(image.width):
            r, g, b, a = pixels[x, y]
            value = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
            color.append(value & 0xFF)
            color.append((value >> 8) & 0xFF)
            alpha.append(a if a > ALPHA_CUTOFF else 0)
    return bytes(color + alpha)


def emit_array(name: str, data: bytes) -> list[str]:
    lines = [f"static const uint8_t {name}_map[] = {{"]
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    lines.append("};")
    return lines


def main() -> None:
    OUT_C.parent.mkdir(parents=True, exist_ok=True)
    entries: list[tuple[str, int, int, bytes]] = []

    for prefix, file_prefix in HEROES:
        for pose, index in HERO_POSES:
            path = SRC / f"ultra-{file_prefix}-{index:02d}-{pose}.png"
            image = load_fitted(path, HERO_W, HERO_H)
            entries.append((f"spr_{prefix}_{pose}", HERO_W, HERO_H, rgb565a8(image)))

    for name, file_name, index in MONSTERS:
        for pose, pose_index in MONSTER_POSES:
            path = SRC / f"monster-{index:02d}-{file_name}-{pose_index:02d}-{pose}.png"
            image = load_fitted(path, MONSTER_W, MONSTER_H)
            entries.append(
                (f"spr_{name}_{pose}", MONSTER_W, MONSTER_H, rgb565a8(image)))

    lines = [
        "// Generated by tools/build_sprites.py. Do not edit by hand.",
        '#include "sprites.h"',
        "",
    ]
    for name, width, height, data in entries:
        lines.extend(emit_array(name, data))
        lines.extend(
            [
                f"static const lv_image_dsc_t {name}_dsc = {{",
                "    .header = {",
                "        .magic = LV_IMAGE_HEADER_MAGIC,",
                "        .cf = LV_COLOR_FORMAT_RGB565A8,",
                "        .flags = 0,",
                f"        .w = {width},",
                f"        .h = {height},",
                f"        .stride = {width * 2},",
                "        .reserved_2 = 0,",
                "    },",
                f"    .data_size = sizeof({name}_map),",
                f"    .data = {name}_map,",
                "    .reserved = NULL,",
                "};",
                "",
            ]
        )

    lines.append("static const lv_image_dsc_t *const HERO_SPRITES[5][8] = {")
    for prefix, _ in HEROES:
        lines.append(
            "    { " + ", ".join(f"&spr_{prefix}_{pose}_dsc" for pose, _ in HERO_POSES) + " },")
    lines.append("};")
    lines.append("")
    lines.append("static const lv_image_dsc_t *const MONSTER_SPRITES[8][5] = {")
    for name, _, _ in MONSTERS:
        lines.append(
            "    { " + ", ".join(f"&spr_{name}_{pose}_dsc" for pose, _ in MONSTER_POSES) + " },")
    lines.append("};")
    lines.append("")
    lines.extend(
        [
            "const lv_image_dsc_t *sprites_hero(uint8_t hero, uint8_t pose)",
            "{",
            "    if (hero >= 5) hero = 0;",
            "    if (pose >= 8) pose = 0;",
            "    return HERO_SPRITES[hero][pose];",
            "}",
            "",
            "const lv_image_dsc_t *sprites_monster(uint8_t stage, uint8_t pose)",
            "{",
            "    if (stage >= 8) stage = 0;",
            "    if (pose >= 5) pose = 0;",
            "    return MONSTER_SPRITES[stage][pose];",
            "}",
            "",
        ]
    )
    OUT_C.write_text("\n".join(lines), encoding="utf-8")

    header = """// Generated by tools/build_sprites.py. Do not edit by hand.
#pragma once

#include <stdint.h>

#include "lvgl.h"

typedef enum {
    SPRITE_POSE_IDLE = 0,
    SPRITE_POSE_FIGHT,
    SPRITE_POSE_FLY,
    SPRITE_POSE_BEAM,
    SPRITE_POSE_CHARGE,
    SPRITE_POSE_KICK,
    SPRITE_POSE_GUARD,
    SPRITE_POSE_VICTORY,
    SPRITE_POSE_COUNT,
} sprite_pose_t;

typedef enum {
    SPRITE_MONSTER_IDLE = 0,
    SPRITE_MONSTER_ATTACK,
    SPRITE_MONSTER_ROAR,
    SPRITE_MONSTER_CHARGE,
    SPRITE_MONSTER_HURT,
    SPRITE_MONSTER_COUNT,
} sprite_monster_pose_t;

const lv_image_dsc_t *sprites_hero(uint8_t hero, uint8_t pose);
const lv_image_dsc_t *sprites_monster(uint8_t stage, uint8_t pose);
"""
    OUT_H.write_text(header, encoding="utf-8")

    total = sum(len(data) for _, _, _, data in entries)
    print(f"Generated {OUT_C.relative_to(ROOT)}: {len(entries)} sprites, {total} bytes payload")
    for name, width, height, data in entries:
        print(f"  {name}: {width}x{height}, {len(data)} bytes")


if __name__ == "__main__":
    main()